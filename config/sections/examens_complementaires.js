import B from "../normes_bio.js";

// Nom écrit dans le texte : « Créatinine » → « créatinine », mais « Hb », « PaCO₂ » inchangés
const nomTexte = (l) => (l.length > 3 && /^[A-ZÀ-Ý][a-zà-ÿ\s]+$/.test(l) ? l.charAt(0).toLowerCase() + l.slice(1) : l);

// Champ numérique de biologie construit à partir de normes_bio.js
const bio = (id, si, extra = {}) => {
  const b = B[id];
  return {
    id,
    type: "nombre",
    label: `${b.label}${b.unite ? ` (${b.unite})` : ""}`,
    decimales: b.decimales ?? 2,
    bornes: b.bornes,
    si,
    phrase: `${nomTexte(b.label)} {valeur}${b.unite ? (b.unite.startsWith("/") ? b.unite : " " + b.unite) : ""}`,
    ...extra,
  };
};

const coche = (x) => `coche('ex_demandes', '${x}')`;

// Résultat d'imagerie : normal / anormal + précision
const imagerie = (id, nom, extra = {}) => [
  {
    id: `${id}_res`,
    type: "choix",
    label: nom.charAt(0).toUpperCase() + nom.slice(1),
    si: coche(id),
    nouvelle: true,
    options: [
      { v: "normal", label: "Normal", texte: `${nom} sans anomalie` },
      { v: "anormal", label: "Anormal", texte: `${nom} anormal${extra.masc ? "" : "e"}[ : {${id}_signes}][ ({${id}_detail})]`, anormal: true },
    ],
  },
  ...(extra.signes ? [{ id: `${id}_signes`, type: "multi", label: "Anomalies", si: `${id}_res == 'anormal'`, sortie: false, options: extra.signes }] : []),
  { id: `${id}_detail`, type: "texte", label: "Résultat / précision", si: `${id}_res == 'anormal'`, sortie: false },
];

